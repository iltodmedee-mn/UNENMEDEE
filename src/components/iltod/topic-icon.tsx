/** The bare icon in `currentColor`. Unknown keys get the "other" (state news) megaphone. */
export function TopicIcon({ topic, className }: { topic: string; className?: string }) {
  return (
    <svg viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth={2} strokeLinecap="round" strokeLinejoin="round" aria-hidden focusable="false" className={className}>
      {TOPIC_ICONS[topic] ?? TOPIC_ICONS.other}
    </svg>
  );
}

/**
 * The label's marker: the icon on a soft tile of the topic's hue (`tile` and `color` are the
 * topic's literal Tailwind classes, see topics.ts). It replaces the 8 px square of Oct 2026.
 */
export function TopicMark({ topic, tile, color, size = "sm", className }: { topic: string; tile: string; color: string; size?: "xs" | "sm" | "md"; className?: string }) {
  const box = size === "md" ? "size-7 rounded-lg" : size === "xs" ? "size-5 rounded-md" : "size-6 rounded-[7px]";
  const icon = size === "md" ? "size-[17px]" : size === "xs" ? "size-[13px]" : "size-[15px]";
  return (
    <span aria-hidden className={cx("inline-flex shrink-0 items-center justify-center", box, tile, color, className)}>
      <TopicIcon topic={topic} className={icon} />
    </span>
  );
}
